"""Derive per-glyph advance widths for the STEINS;GATE (Steam) font (3072x6000, 64x125 cells of 48px).

Usage: python gen_widths.py <patched-impacto-checkout> <FONT.PNG> [sg-pc|sg0-pc]

The optional profile (default sg-pc) picks the atlas layout: STEINS;GATE 0 (sg0-pc) uses the same cells and the same
Latin layout in rows 0..3, in a 3072x3840 atlas of 80 rows (system.mpk id 9, font_a.dds; Pillow reads the DDS directly).

Needs Pillow (`pip install pillow`). FONT.PNG is the font atlas (system.mpk id 9) that the user extracted from their
own copy of the game (see mpk_tool.py); nothing from the game is stored in this repository. The result is written to
<checkout>/profiles/sg-pc/font-widths.lua.

The Chaos;Child advance table the profile started from describes another typeface, so round Latin letters ("o", "O",
"?") were cut off at the right edge: SingleSheetFont crops each glyph quad from the left edge of its cell, so a glyph
needs an advance that covers its ink. Measurement of the atlas (alpha > 24):
  * ids 1..226 (rows 0..2 and the first 34 cells of row 3) are the proportional Latin letters, digits and punctuation
    in two sets (rows 0-1 small, rows 2-3 large; the script text uses the large one), drawn left aligned within the
    cell -> advance = ink right edge + 3 (the sprite crop margin plus a little air; an empty cell gets 16);
  * id 63 is the half-width space -> 16;
  * id 0 and every other cell (kana, kanji, full-width punctuation that sits in a corner of the em box) -> 48.
"""
import os
import sys

from PIL import Image

if len(sys.argv) not in (3, 4):
    sys.exit(__doc__)
root, font = sys.argv[1], sys.argv[2]
profile = sys.argv[3] if len(sys.argv) == 4 else "sg-pc"
LAYOUTS = {  # rows, Lua table name, atlas name in the header comment
    "sg-pc": (125, "SgPcAdvanceOverrides", "FONT.PNG"),
    "sg0-pc": (80, "Sg0PcAdvanceOverrides", "font_a.dds"),
}
if profile not in LAYOUTS:
    sys.exit(__doc__)
CELL, COLS = 48, 64
ROWS, TABLE, ATLAS = LAYOUTS[profile]
EM, SPACE, PAD = 48, 16, 3
PROPORTIONAL_END = 227  # ids 1..226

a = Image.open(font).convert("RGBA").getchannel("A").point(lambda v: 255 if v > 24 else 0)
assert a.size == (COLS * CELL, ROWS * CELL), a.size

over = {}
for g in range(1, PROPORTIONAL_END):
    r, c = divmod(g, COLS)
    bb = a.crop((c * CELL, r * CELL, c * CELL + CELL, r * CELL + CELL)).getbbox()
    if g == 63 or bb is None:
        width = SPACE
    else:
        width = min(EM, bb[2] + PAD)
    if width != EM:
        over[g] = width

lines = ["-- Generated by tools/impacto/sghd/gen_widths.py from system.mpk %s (id 9); do not edit." % ATLAS,
         "-- Advance widths in 48px-em units; every glyph not listed has advance 48.",
         "root.%s = {" % TABLE]
row = []
for g in sorted(over):
    row.append("[%d]=%d" % (g, over[g]))
    if len(row) == 12:
        lines.append("    " + ", ".join(row) + ",")
        row = []
if row:
    lines.append("    " + ", ".join(row) + ",")
lines.append("};")
out = os.path.join(root, "profiles", profile, "font-widths.lua")
with open(out, "w", encoding="utf8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out, len(over), "overrides")
