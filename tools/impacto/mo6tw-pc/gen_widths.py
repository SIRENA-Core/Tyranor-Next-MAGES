"""Derive per-glyph advance widths for the Memories Off 6 PC fonts (3072x6000, 64x125 cells of 48px).

Usage: python gen_widths.py <patched-impacto-checkout> <font.png> <font_ht.png> <font_kt.png>

Needs Pillow (`pip install pillow`). The three PNGs are the font atlases (system.cpk ids 10/11/12) that the user
extracted from their own copy of the game; nothing from the game is stored in this repository. The result is
written to <checkout>/profiles/mo6tw-pc/font-widths.lua.

The PC game ships no advance-width table, so widths are derived from the atlases:
SingleSheetFont crops each glyph quad from the left edge of its cell, so a glyph must
be given enough advance to cover its ink. Measurement of all 8000 cells (alpha > 24) shows:
  * row 1 (ids 64..127) holds half-width symbols, left aligned within a 24px half cell
    (ink right edge <= 24 in all three fonts) -> advance 26 (24px half cell + 2px for the sprite crop margin);
  * id 63 is the half-width space -> 24;
  * every other cell is a full-width design (alnum rows 0/2 are drawn centred in the 48px
    cell, kanji/kana fill it, CJK punctuation sits at a corner of the em box) -> advance 48.
The script verifies that all three fonts agree and writes profiles/mo6tw-pc/font-widths.lua.
"""
import sys, os
from PIL import Image

if len(sys.argv) != 5:
    sys.exit(__doc__)
root, fonts = sys.argv[1], sys.argv[2:5]
CELL, COLS, ROWS = 48, 64, 125
EM, HALF = 48, 26

def advance_table(path):
    a = Image.open(path).convert("RGBA").getchannel("A").point(lambda v: 255 if v > 24 else 0)
    assert a.size == (COLS * CELL, ROWS * CELL), a.size
    adv = {}
    for g in range(COLS * ROWS):
        r, c = divmod(g, COLS)
        bb = a.crop((c * CELL, r * CELL, c * CELL + CELL, r * CELL + CELL)).getbbox()
        if g == 63:
            adv[g] = HALF
        elif 64 <= g < 128:
            adv[g] = HALF if (bb is None or bb[2] <= HALF) else EM
        else:
            adv[g] = EM
    return adv

tables = [advance_table(p) for p in fonts]
for t in tables[1:]:
    assert t == tables[0], "fonts disagree: derive per-language tables"
over = {g: w for g, w in tables[0].items() if w != EM}
lines = ["-- Generated by tyn gen_widths.py from system.cpk font/font_ht/font_kt (ids 10/11/12); do not edit.",
         "-- Advance widths in 48px-em units; every glyph not listed has advance 48.",
         "root.Mo6PcAdvanceOverrides = {"]
ids = sorted(over)
row = []
for g in ids:
    row.append("[%d]=%d" % (g, over[g]))
    if len(row) == 12:
        lines.append("    " + ", ".join(row) + ","); row = []
if row: lines.append("    " + ", ".join(row) + ",")
lines.append("};")
out = os.path.join(root, "profiles", "mo6tw-pc", "font-widths.lua")
open(out, "w", encoding="utf8", newline="\n").write("\n".join(lines) + "\n")
print("wrote", out, len(over), "overrides")
