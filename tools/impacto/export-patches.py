#!/usr/bin/env python3
"""Regenerate engine/impacto/patches/ from a branch in an upstream Impacto checkout.

The branch must be linear and based on the pinned revision of source-lock.json (one commit
per patch, no merges). Output is stable `git format-patch` text (no version signature, zero
commit ids, full index lines, no renames, diff/config options pinned), so unchanged commits
export byte-identical files.

Everything is generated and validated in a temporary directory first: the series is replayed
on the pinned revision and must reproduce the branch tip's tree exactly, and the staged
result must pass the same gate the build uses (verify-upstream load_series). Only then are
the files published: new/changed patches, `series` and source-lock.json are each written via
a temporary file + os.replace, and patches that dropped out of the series are removed last.
Does not modify the checkout.
"""
import argparse
import json
from pathlib import Path
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
import impacto_common  # noqa: E402

ROOT = impacto_common.ROOT
verifier = impacto_common.load_verifier()

SERIES_HEADER = (
    "# Ordered patch series applied on top of the pinned Impacto revision (see README.md).\n"
    "# Generated by tools/impacto/export-patches.py; edit patches as commits, then re-export.\n"
)
# Everything that could vary with user configuration or Git version is pinned explicitly.
FORMAT_OPTIONS = (
    "-U3", "--inter-hunk-context=0",
    "-N", "--no-signature", "--zero-commit", "--no-stat", "--binary", "--full-index", "--no-renames",
    "--no-base", "--no-cover-letter", "--no-notes", "--no-color", "--no-ext-diff", "--no-textconv",
    "--diff-algorithm=myers", "--src-prefix=a/", "--dst-prefix=b/", "--filename-max-length=64",
    "--start-number=1", "--subject-prefix=PATCH",
)


def commit_range(source, revision, branch):
    tip = verifier.git(source, "rev-parse", "--verify", f"{branch}^{{commit}}").strip()
    try:
        verifier.git(source, "merge-base", "--is-ancestor", revision, tip)
    except RuntimeError:
        raise RuntimeError(f"{branch} is not based on the pinned revision {revision}") from None
    if verifier.git(source, "rev-list", "--merges", f"{revision}..{tip}").strip():
        raise RuntimeError("The patch branch must be linear (merge commits found); rebase it")
    return tip


# Configuration that would otherwise change what `git format-patch` prints (command-line options win over config,
# but not every one of these has an option).
CONFIG_PINS = ("-c", "diff.context=3", "-c", "diff.interHunkContext=0", "-c", "core.quotepath=false",
               "-c", "diff.noprefix=false", "-c", "diff.mnemonicPrefix=false", "-c", "diff.relative=false")


def format_patches(source, revision, tip, output):
    verifier.git(source, *CONFIG_PINS, "format-patch", *FORMAT_OPTIONS, "-o", str(output), f"{revision}..{tip}")
    files = sorted(output.glob("*.patch"))
    series = []
    for path in files:
        if not verifier.PATCH_NAME.fullmatch(path.name):
            raise RuntimeError(f"Unusable patch name {path.name!r}; give the commit a descriptive ASCII subject")
        series.append({"file": path.name, "sha256": verifier.sha256_file(path), "path": path})
    return series


def publish(directory, lock, staged_directory, staged_lock, series):
    """Move the validated staged result into the repository. New/changed files first, stale ones last."""
    directory.mkdir(parents=True, exist_ok=True)
    for patch in series:
        impacto_common.atomic_write(directory / patch["file"], (staged_directory / patch["file"]).read_bytes())
    impacto_common.atomic_write(directory / verifier.SERIES_FILE, (staged_directory / verifier.SERIES_FILE).read_bytes())
    impacto_common.atomic_write(lock, staged_lock.read_bytes())
    keep = {patch["file"] for patch in series}
    for old in directory.glob("*.patch"):
        if old.name not in keep:
            old.unlink()


def export(source, lock, branch="HEAD"):
    source = source.resolve()
    lock = lock.resolve()
    metadata = json.loads(lock.read_text(encoding="utf-8"))
    revision = metadata["impacto"]["revision"]
    name = metadata.get("patches", {}).get("directory", "patches")
    directory = verifier.resolve_patch_directory(lock, name)
    if Path(verifier.git(source, "rev-parse", "--show-toplevel").strip()).resolve() != source:
        raise RuntimeError(f"Source must be the checkout root: {source}")
    tip = commit_range(source, revision, branch)
    with tempfile.TemporaryDirectory(prefix="impacto-export-") as temporary:
        temporary = Path(temporary)
        formatted = temporary / "formatted"
        formatted.mkdir()
        series = format_patches(source, revision, tip, formatted)
        replayed = verifier.expected_tree(source, series, base=revision)
        branch_tree = verifier.git(source, "rev-parse", f"{tip}^{{tree}}").strip()
        if replayed != branch_tree:
            raise RuntimeError("The exported series does not reproduce the branch tree "
                               f"(replayed {replayed}, branch {branch_tree}); check mode/binary/submodule changes")
        # Stage the complete result next to a lock copy at the same relative layout, and run the build's own
        # gate (names, order, series file, SHA-256, stray files) on it before anything is published.
        stage = temporary / "stage"
        staged_lock = stage / lock.name
        staged_directory = verifier.resolve_patch_directory(staged_lock, name)
        staged_directory.mkdir(parents=True)
        for patch in series:
            (staged_directory / patch["file"]).write_bytes(patch["path"].read_bytes())
        (staged_directory / verifier.SERIES_FILE).write_bytes(
            (SERIES_HEADER + "".join(p["file"] + "\n" for p in series)).encode("utf-8"))
        metadata["patches"] = {"directory": name,
                               "series": [{"file": p["file"], "sha256": p["sha256"]} for p in series]}
        staged_lock.write_bytes((json.dumps(metadata, indent=2, ensure_ascii=True) + "\n").encode("utf-8"))
        verifier.load_series(staged_lock)
        publish(directory, lock, staged_directory, staged_lock, series)
    verifier.load_series(lock)  # the published result must itself pass the gate
    return {"revision": revision, "tip": tip, "tree": branch_tree, "patches": verifier.describe_series(series)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="upstream checkout holding the patch branch")
    parser.add_argument("--branch", default="HEAD", help="branch or commit whose history on top of the pinned revision is exported")
    parser.add_argument("--lock", type=Path, default=ROOT / "engine/impacto/source-lock.json")
    args = parser.parse_args()
    return impacto_common.run_cli(lambda: export(args.source, args.lock, args.branch),
                                  failure="Impacto patch export failed")


if __name__ == "__main__":
    sys.exit(main())
